// Training categories supplement the original source type; they never rewrite it.
export const SUBTYPES = {
  '逻辑填空': ['单空填空','双空填空','三空及以上','未细分'],
  '片段阅读': ['主旨概括','意图判断','细节理解','标题选择','词句理解','下文推断','态度观点','未细分'],
  '语句表达': ['语句排序','语句填空','病句辨析','语句衔接','未细分'],
  '数学运算': ['行程问题','工程问题','经济利润','排列组合','概率问题','几何问题','容斥问题','最值问题','年龄问题','浓度问题','周期问题','和差倍比','数列与计数','基础计算','未细分'],
  '图形推理': ['空间重构','位置规律','样式规律','对称属性','笔画数量','点线面数量','元素数量','曲直与开放封闭','未细分'],
  '定义判断': ['单定义','多定义','未细分'],
  '类比推理': ['语义关系','逻辑关系','语法关系','常识关系','未细分'],
  '逻辑判断': ['加强论证','削弱论证','前提假设','解释原因','结论推断','翻译推理','组合排列','未细分'],
  '增长': ['基期量','现期量','增长量计算','增长量比较','增长率计算','增长率比较','间隔增长率','年均增长率','混合增长率','未细分'],
  '比重': ['现期比重','基期比重','两期比重','未细分'],
  '平均数': ['现期平均数','基期平均数','平均数增长率','两期平均数','未细分'],
  '倍数': ['现期倍数','基期倍数','未细分'],
  '综合': ['综合判断','直接查找','其他计算','未细分'],
};
export const text = html => String(html||'').replace(/<[^>]*>/g,' ').replace(/&(?:nbsp|gt|lt|amp);/g,' ').replace(/\s+/g,' ').trim();
const hit = (value, rules) => rules.find(([pattern])=>pattern.test(value))?.[1];
export function classify(q) {
  let group=q.type, tag;
  const stem=text(q.stem), explanation=text(q.explanation), intro=explanation.split(/A项[：:]|选项A[：:]/)[0].slice(0,700);
  const prompt=stem.slice(-260);
  if(q.module==='资料分析') {
    if(/下列|以下/.test(prompt)&&/(?:说法|表述|判断|信息|推断).{0,35}(?:正确|错误|不正确|能够|不能|符合|得到)|(?:正确|错误|不正确).{0,15}(?:说法|表述)/.test(prompt)) {group='综合';tag='综合判断';}
    else {
      const explicit=intro.match(/(?:本题为|判定本题为|判定为|本题属于|考查)([^。；]{0,35}?)(?:问题|题[，。])/);
      const kind=explicit?.[1]||'';
      tag=hit(kind,[
        [/平均数增长率|平均.*增长率/,'平均数增长率'],[/基期平均/,'基期平均数'],[/两期平均/,'两期平均数'],[/现期平均|平均数/,'现期平均数'],
        [/两期比重|比重差|比重变化/,'两期比重'],[/基期比重/,'基期比重'],[/现期比重|比重/,'现期比重'],
        [/基期倍数/,'基期倍数'],[/现期倍数|倍数/,'现期倍数'],
        [/间隔增长率|间隔增长/,'间隔增长率'],[/年均增长/,'年均增长率'],[/混合增长/,'混合增长率'],
        [/增长量.*比较/,'增长量比较'],[/增长率.*比较/,'增长率比较'],[/增长量/,'增长量计算'],[/增长率/,'增长率计算'],
        [/基期量|基期计算/,'基期量'],[/现期量|现期计算/,'现期量'],[/直接查找|直接读数/,'直接查找'],[/简单计算|现期和差/,'其他计算'],
      ]);
      if(tag)group=['现期比重','基期比重','两期比重'].includes(tag)?'比重':/平均/.test(tag)?'平均数':/倍数/.test(tag)?'倍数':['直接查找','其他计算'].includes(tag)?'综合':'增长';
    }
  } else if(group==='逻辑填空') {
    const n=(String(q.stem).match(/class="exam-blank"/g)||[]).length;
    tag=n>=3||/第三空/.test(explanation)?'三空及以上':n===2||/第二空/.test(explanation)?'双空填空':n===1||/第一空|横线处/.test(intro)?'单空填空':null;
  } else if(group==='片段阅读') {
    tag=hit(prompt,[[/标题|题目最适合/,'标题选择'],[/下文|接下来|接着.*讲述/,'下文推断'],[/态度|观点是|持.*观点/,'态度观点'],[/意在|意图|旨在/,'意图判断'],[/主旨|主要.{0,8}(?:说明|强调|表达|介绍|讲述|论述)|核心观点|中心意思/,'主旨概括'],[/词语|词句|划线|画线|含义|指的是|意指/,'词句理解'],[/符合|不符合|正确|错误|无法|不能|可以得出|可知/,'细节理解']]);
  } else if(group==='语句表达') {
    tag=hit(prompt+' '+intro.slice(0,180),[[/语病|病句/,'病句辨析'],[/排序|排列|顺序|语序/,'语句排序'],[/填入|填在|填到|填进|填上|横线处/,'语句填空'],[/衔接/,'语句衔接']]);
  } else if(group==='数学运算') {
    const rules=[[/行程问题/,'行程问题'],[/工程问题/,'工程问题'],[/经济(?:利润)?问题|利润问题/,'经济利润'],[/排列组合问题|排列组合/,'排列组合'],[/概率问题|概率为|概率等于/,'概率问题'],[/几何问题/,'几何问题'],[/容斥|集合问题/,'容斥问题'],[/最值问题|极值问题/,'最值问题'],[/年龄问题/,'年龄问题'],[/浓度问题|溶液问题/,'浓度问题'],[/周期问题/,'周期问题'],[/和差倍比|比例问题/,'和差倍比'],[/数列问题|计数问题/,'数列与计数']];
    tag=hit(intro,rules)||hit(stem,[
      [/概率|随机.{0,12}(?:抽|选|取)|可能性为/,'概率问题'],[/多少种|几种|种不同.*(?:方法|方式)|排列|组合/,'排列组合'],
      [/浓度|溶液|溶质/,'浓度问题'],[/年龄|岁.{0,15}(?:今年|年后|年前)|今年.{0,10}岁/,'年龄问题'],
      [/(?:完成|加工|生产|修建).{0,12}(?:工程|任务).{0,20}(?:天|小时)|(?:工程|任务).{0,30}(?:合作|合做|单独)/,'工程问题'],
      [/千米\/小时|公里\/小时|速度|相向|追及|相遇|往返|每小时.{0,8}(?:千米|公里)/,'行程问题'],
      [/利润|售价|进价|成本|打.{0,3}折|定价|盈利/,'经济利润'],
      [/面积|周长|体积|圆柱|正方形|长方形|三角形|半径|直径/,'几何问题'],
      [/至少|至多|最少|最多/,'最值问题'],
    ]);
  } else if(group==='图形推理') {
    tag=hit(stem+' '+intro,[
      [/折叠|展开图|立体图|空间重构|六面体|四面体/,'空间重构'],[/旋转|平移|顺时针|逆时针|位置规律|镜像/,'位置规律'],
      [/黑白运算|求同|求异|去同存异|遍历|叠加/,'样式规律'],[/对称轴|中心对称|轴对称/,'对称属性'],
      [/笔画数|一笔画|两笔画|几笔画|笔画规律/,'笔画数量'],[/(?:交点|端点|直线|曲线|线段|封闭面|封闭区域).{0,12}(?:数量|个数|分别|依次)|点线面/,'点线面数量'],
      [/元素.{0,12}(?:数量|个数)|素.{0,8}(?:种类|数量)/,'元素数量'],[/曲直性|曲直|开放性|封闭性/,'曲直与开放封闭'],
    ]);
  } else if(group==='定义判断') {
    tag=hit(intro,[[/多定义/,'多定义'],[/单定义/,'单定义']]);
    if(!tag&&(stem.match(/(?:是指|指的是)/g)||[]).length===1)tag='单定义';
    // Multiple explicit definitional sentences are stronger evidence than the generic question ending.
    if((stem.match(/(?:是指|指的是|称为)/g)||[]).length>=2)tag='多定义';
  } else if(group==='类比推理') {
    tag=hit(intro,[ [/近义|反义|比喻义|词义|语义关系/,'语义关系'],[/主谓|动宾|偏正|语法关系/,'语法关系'],[/常识关系|作者|作品|产地|历史|地理|物理|化学|生物|对应关系/,'常识关系'],[/并列|包含|包容|交叉|全异|种属|组成|逻辑关系/,'逻辑关系'] ]);
  } else if(group==='逻辑判断') {
    tag=hit(prompt,[[/前提|假设|必需的条件|必须补充|必要的条件/,'前提假设'],[/削弱|质疑|反驳/,'削弱论证'],[/加强|支持|支撑/,'加强论证'],[/解释|说明.*原因/,'解释原因']])||hit(intro,[[/组合排列|排列组合|组合推理/,'组合排列'],[/翻译题干|翻译推理|充分条件|必要条件|逆否/,'翻译推理']])||hit(prompt,[[/推出|推断|得出|一定|可知/,'结论推断']]);
  }
  return {group,tag:tag||((SUBTYPES[group])?'未细分':group)};
}
